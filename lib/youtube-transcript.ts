import { jsPDF } from 'jspdf';

export interface TranscriptSegment {
  index: number;
  startMs: number;
  durationMs: number;
  endMs: number;
  text: string;
}

export interface CaptionLanguageOption {
  code: string;
  name: string;
  isAutoGenerated: boolean;
}

export interface TranscriptResultData {
  videoId: string;
  originalUrl: string;
  title: string;
  author: string;
  thumbnail: string;
  durationSeconds: number;
  language: string;
  languageName: string;
  availableLanguages: CaptionLanguageOption[];
  segments: TranscriptSegment[];
  wordCount: number;
  processingTimeMs: number;
  engine: string;
}

export type TranscriptExportFormat = 'txt' | 'srt' | 'vtt' | 'pdf' | 'csv';

/**
 * Extract an 11-character YouTube Video ID from any YouTube URL or raw ID.
 */
export function extractYouTubeVideoId(input: string): string | null {
  const trimmed = input.trim();
  if (!trimmed) return null;

  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) {
    return trimmed;
  }

  try {
    const withProtocol = /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
    const url = new URL(withProtocol);
    const host = url.hostname.toLowerCase().replace(/^www\./, '');

    if (host === 'youtu.be') {
      const id = url.pathname.split('/').filter(Boolean)[0];
      return id && /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
    }

    if (
      host === 'youtube.com' ||
      host === 'm.youtube.com' ||
      host === 'music.youtube.com' ||
      host === 'youtube-nocookie.com'
    ) {
      const vParam = url.searchParams.get('v');
      if (vParam && /^[a-zA-Z0-9_-]{11}$/.test(vParam)) {
        return vParam;
      }

      const parts = url.pathname.split('/').filter(Boolean);
      if (parts.length >= 2 && ['shorts', 'embed', 'live', 'v', 'e'].includes(parts[0])) {
        const candidate = parts[1];
        if (/^[a-zA-Z0-9_-]{11}$/.test(candidate)) {
          return candidate;
        }
      }
    }
  } catch {
    // Fallback regex extraction
  }

  const regexMatch = trimmed.match(
    /(?:v=|youtu\.be\/|\/shorts\/|\/live\/|\/embed\/)([a-zA-Z0-9_-]{11})/
  );
  return regexMatch ? regexMatch[1] : null;
}

/**
 * Format milliseconds into human-readable timeline timestamp (e.g. 01:24 or 1:05:12).
 */
export function formatDisplayTimestamp(ms: number): string {
  const totalSeconds = Math.max(0, Math.floor(ms / 1000));
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  if (hours > 0) {
    return `${hours}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
  }
  return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

export function formatDurationSeconds(totalSeconds: number): string {
  if (!Number.isFinite(totalSeconds) || totalSeconds <= 0) return 'Unknown length';
  return formatDisplayTimestamp(totalSeconds * 1000);
}

/**
 * Format milliseconds for SRT (HH:MM:SS,mmm) or VTT (HH:MM:SS.mmm).
 */
function formatSubtitleTimestamp(ms: number, separator: ',' | '.'): string {
  const safeMs = Math.max(0, Math.round(ms));
  const hours = Math.floor(safeMs / 3600000);
  const minutes = Math.floor((safeMs % 3600000) / 60000);
  const seconds = Math.floor((safeMs % 60000) / 1000);
  const millis = safeMs % 1000;

  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(
    seconds
  ).padStart(2, '0')}${separator}${String(millis).padStart(3, '0')}`;
}

export function buildCopyText(
  segments: TranscriptSegment[],
  includeTimestamps: boolean
): string {
  if (!segments.length) return '';
  if (includeTimestamps) {
    return segments
      .map((seg) => `[${formatDisplayTimestamp(seg.startMs)}] ${seg.text}`)
      .join('\n');
  }
  return segments.map((seg) => seg.text).join(' ');
}

export function buildTxtContent(
  data: TranscriptResultData,
  includeTimestamps: boolean = true
): string {
  const header = [
    data.title,
    `Channel: ${data.author}`,
    `Video URL: ${data.originalUrl}`,
    `Language: ${data.languageName} (${data.language})`,
    '------------------------------------------------------------',
    '',
  ].join('\n');

  return header + buildCopyText(data.segments, includeTimestamps);
}

export function buildSrtContent(segments: TranscriptSegment[]): string {
  return segments
    .map((seg, idx) => {
      const start = formatSubtitleTimestamp(seg.startMs, ',');
      const end = formatSubtitleTimestamp(Math.max(seg.endMs, seg.startMs + 500), ',');
      return `${idx + 1}\n${start} --> ${end}\n${seg.text}`;
    })
    .join('\n\n');
}

export function buildVttContent(
  segments: TranscriptSegment[],
  title?: string
): string {
  const header = title ? `WEBVTT - ${title}\n\n` : 'WEBVTT\n\n';
  const body = segments
    .map((seg) => {
      const start = formatSubtitleTimestamp(seg.startMs, '.');
      const end = formatSubtitleTimestamp(Math.max(seg.endMs, seg.startMs + 500), '.');
      return `${start} --> ${end}\n${seg.text}`;
    })
    .join('\n\n');
  return header + body;
}

function escapeCsvField(value: string): string {
  const str = String(value ?? '');
  if (/[",\r\n]/.test(str)) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

export function buildCsvContent(segments: TranscriptSegment[]): string {
  const rows = [
    ['Index', 'Start Time', 'End Time', 'Start (ms)', 'Duration (s)', 'Transcript Text'].join(','),
    ...segments.map((seg, idx) =>
      [
        String(idx + 1),
        escapeCsvField(formatSubtitleTimestamp(seg.startMs, '.')),
        escapeCsvField(formatSubtitleTimestamp(seg.endMs, '.')),
        String(seg.startMs),
        (seg.durationMs / 1000).toFixed(2),
        escapeCsvField(seg.text),
      ].join(',')
    ),
  ];
  // UTF-8 BOM ensures Excel opens Unicode transcripts (Bengali, Arabic, CJK, etc.) cleanly
  return '\uFEFF' + rows.join('\r\n');
}

function containsNonLatin1(text: string): boolean {
  return /[^\u0000-\u00FF]/.test(text);
}

function sanitizeFilenameBase(
  title: string,
  videoId: string,
  filenameSuffix?: string
): string {
  const cleaned = title
    .replace(/[^\w\u0980-\u09FF.\-\s]+/g, '')
    .trim()
    .replace(/\s+/g, '_')
    .slice(0, 50);
  const base = cleaned || `youtube_transcript_${videoId}`;
  if (!filenameSuffix) return base;
  const safeSuffix = filenameSuffix.replace(/[^a-zA-Z0-9_-]+/g, '_').replace(/^_+|_+$/g, '');
  return safeSuffix ? `${base}_${safeSuffix}` : base;
}

function triggerBlobDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    a.remove();
    URL.revokeObjectURL(url);
  }, 1500);
}

/**
 * Render non-Latin scripts (e.g., Bengali, Hindi, Arabic, Japanese) onto high-DPI canvases
 * and embed as paginated A4 pages inside jsPDF so Unicode glyphs never corrupt.
 */
function buildUnicodePdf(
  data: TranscriptResultData,
  includeTimestamps: boolean
): jsPDF {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  const pageWidthPt = doc.internal.pageSize.getWidth();
  const pageHeightPt = doc.internal.pageSize.getHeight();

  const scale = 2;
  const pxPerPt = 96 / 72;
  const canvasWidth = Math.round(pageWidthPt * pxPerPt * scale);
  const canvasHeight = Math.round(pageHeightPt * pxPerPt * scale);
  const marginX = Math.round(44 * pxPerPt * scale);
  const marginTop = Math.round(48 * pxPerPt * scale);
  const marginBottom = Math.round(48 * pxPerPt * scale);
  const maxContentWidth = canvasWidth - marginX * 2;

  const createPageCanvas = () => {
    const canvas = document.createElement('canvas');
    canvas.width = canvasWidth;
    canvas.height = canvasHeight;
    const ctx = canvas.getContext('2d')!;
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, canvasWidth, canvasHeight);
    return { canvas, ctx };
  };

  const wrapLines = (
    ctx: CanvasRenderingContext2D,
    text: string,
    maxWidth: number
  ): string[] => {
    const words = text.split(/\s+/);
    const lines: string[] = [];
    let current = '';
    for (const word of words) {
      const test = current ? `${current} ${word}` : word;
      if (ctx.measureText(test).width > maxWidth && current) {
        lines.push(current);
        current = word;
      } else {
        current = test;
      }
    }
    if (current) lines.push(current);
    return lines.length ? lines : [''];
  };

  let { canvas, ctx } = createPageCanvas();
  let y = marginTop;
  let pageCount = 1;

  const pushPage = () => {
    const imgData = canvas.toDataURL('image/jpeg', 0.92);
    if (pageCount > 1) doc.addPage();
    doc.addImage(imgData, 'JPEG', 0, 0, pageWidthPt, pageHeightPt);
    pageCount += 1;
    ({ canvas, ctx } = createPageCanvas());
    y = marginTop;
  };

  // Title
  ctx.fillStyle = '#0F172A';
  ctx.font = `700 ${16 * scale * pxPerPt}px system-ui, -apple-system, "Segoe UI", sans-serif`;
  for (const line of wrapLines(ctx, data.title, maxContentWidth)) {
    ctx.fillText(line, marginX, y);
    y += 22 * scale * pxPerPt;
  }

  // Metadata
  ctx.fillStyle = '#475569';
  ctx.font = `400 ${10 * scale * pxPerPt}px system-ui, -apple-system, "Segoe UI", sans-serif`;
  const metaLine = `${data.author} · ${data.languageName} · ${data.segments.length} segments · ${data.originalUrl}`;
  for (const line of wrapLines(ctx, metaLine, maxContentWidth)) {
    ctx.fillText(line, marginX, y);
    y += 15 * scale * pxPerPt;
  }

  y += 8 * scale * pxPerPt;
  ctx.strokeStyle = '#E2E8F0';
  ctx.lineWidth = scale;
  ctx.beginPath();
  ctx.moveTo(marginX, y);
  ctx.lineTo(canvasWidth - marginX, y);
  ctx.stroke();
  y += 20 * scale * pxPerPt;

  const lineHeight = 16 * scale * pxPerPt;
  const tsColWidth = includeTimestamps ? 68 * scale * pxPerPt : 0;

  for (const seg of data.segments) {
    ctx.font = `400 ${10.5 * scale * pxPerPt}px system-ui, -apple-system, "Segoe UI", sans-serif`;
    const wrapped = wrapLines(ctx, seg.text, maxContentWidth - tsColWidth);
    const blockHeight = wrapped.length * lineHeight + 8 * scale * pxPerPt;

    if (y + blockHeight > canvasHeight - marginBottom) {
      pushPage();
    }

    if (includeTimestamps) {
      ctx.fillStyle = '#DC2626';
      ctx.font = `600 ${9.5 * scale * pxPerPt}px ui-monospace, SFMono-Regular, Menlo, monospace`;
      ctx.fillText(formatDisplayTimestamp(seg.startMs), marginX, y);
    }

    ctx.fillStyle = '#1E293B';
    ctx.font = `400 ${10.5 * scale * pxPerPt}px system-ui, -apple-system, "Segoe UI", sans-serif`;
    wrapped.forEach((line, i) => {
      ctx.fillText(line, marginX + tsColWidth, y + i * lineHeight);
    });

    y += blockHeight;
  }

  const lastImg = canvas.toDataURL('image/jpeg', 0.92);
  if (pageCount > 1) doc.addPage();
  doc.addImage(lastImg, 'JPEG', 0, 0, pageWidthPt, pageHeightPt);

  return doc;
}

function buildVectorPdf(
  data: TranscriptResultData,
  includeTimestamps: boolean
): jsPDF {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 44;
  const maxWidth = pageWidth - margin * 2;
  let y = 52;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(15, 23, 42);
  const titleLines: string[] = doc.splitTextToSize(data.title, maxWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 19 + 4;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(71, 85, 105);
  const metaLines: string[] = doc.splitTextToSize(
    `${data.author}  ·  ${data.languageName}  ·  ${data.segments.length} segments  ·  ${data.originalUrl}`,
    maxWidth
  );
  doc.text(metaLines, margin, y);
  y += metaLines.length * 13 + 8;

  doc.setDrawColor(226, 232, 240);
  doc.line(margin, y, pageWidth - margin, y);
  y += 20;

  const tsOffset = includeTimestamps ? 58 : 0;
  const textWidth = maxWidth - tsOffset;

  for (const seg of data.segments) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10.5);
    const wrapped: string[] = doc.splitTextToSize(seg.text, textWidth);
    const blockHeight = wrapped.length * 15 + 7;

    if (y + blockHeight > pageHeight - 48) {
      doc.addPage();
      y = 52;
    }

    if (includeTimestamps) {
      doc.setFont('courier', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(220, 38, 38);
      doc.text(formatDisplayTimestamp(seg.startMs), margin, y);
    }

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10.5);
    doc.setTextColor(30, 41, 59);
    doc.text(wrapped, margin + tsOffset, y);
    y += blockHeight;
  }

  return doc;
}

export function downloadTranscriptFile(
  data: TranscriptResultData,
  format: TranscriptExportFormat,
  includeTimestamps: boolean = true,
  filenameSuffix?: string
): void {
  const baseName = sanitizeFilenameBase(data.title, data.videoId, filenameSuffix);

  if (format === 'txt') {
    const content = buildTxtContent(data, includeTimestamps);
    triggerBlobDownload(new Blob([content], { type: 'text/plain;charset=utf-8' }), `${baseName}.txt`);
    return;
  }

  if (format === 'srt') {
    const content = buildSrtContent(data.segments);
    triggerBlobDownload(
      new Blob([content], { type: 'application/x-subrip;charset=utf-8' }),
      `${baseName}.srt`
    );
    return;
  }

  if (format === 'vtt') {
    const content = buildVttContent(data.segments, data.title);
    triggerBlobDownload(new Blob([content], { type: 'text/vtt;charset=utf-8' }), `${baseName}.vtt`);
    return;
  }

  if (format === 'csv') {
    const content = buildCsvContent(data.segments);
    triggerBlobDownload(new Blob([content], { type: 'text/csv;charset=utf-8' }), `${baseName}.csv`);
    return;
  }

  if (format === 'pdf') {
    const needsUnicodePdf =
      containsNonLatin1(data.title) ||
      containsNonLatin1(data.author) ||
      containsNonLatin1(data.languageName) ||
      data.segments.some((s) => containsNonLatin1(s.text));
    const doc = needsUnicodePdf
      ? buildUnicodePdf(data, includeTimestamps)
      : buildVectorPdf(data, includeTimestamps);
    doc.save(`${baseName}.pdf`);
  }
}
